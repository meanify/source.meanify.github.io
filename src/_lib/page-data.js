// Computed data shared by every page that uses layouts/base.njk:
// translated pages in src/pages/ (keyed by `pageKey`) and articles in src/insights/
// (which have `pageKey: "article"` and an `article` record from src/_data/articles.js).

// Eleventy may evaluate computed data before `article` is resolved, so article
// pages fall back to empty values until it is.
const isArticle = (data) => data.pageKey === "article";
const articleOf = (data) => data.article || { alternates: {}, title: "", description: "", faqs: [] };

// URL of this page in each language that has it.
export function alternates(data) {
  if (isArticle(data)) return articleOf(data).alternates;
  return data.site.pages[data.pageKey];
}

export function pageMeta(data) {
  if (isArticle(data)) {
    const a = articleOf(data);
    return { title: `${a.title} | Meanify`, description: a.description };
  }
  return data.i18n[data.lang].meta[data.pageKey];
}

// Social share image generated by scripts/og-images.js.
export function ogPath(data) {
  const name = isArticle(data) ? `article-${articleOf(data).translationKey}` : data.pageKey;
  return `/og/${data.lang}/${name}.png`;
}

export const computed = {
  t: (data) => data.i18n[data.lang],
  alternates: (data) => alternates(data),
  meta: (data) => pageMeta(data),
  ogPath: (data) => ogPath(data),
  pageUrl: (data) => alternates(data)[data.lang],
  homeUrl: (data) => data.site.pages.home[data.lang],
  jsonld: (data) => buildJsonLd(data),
  // Service pages mention the service in the prefilled WhatsApp message.
  svc: (data) => data.i18n[data.lang].services[data.pageKey],
  waUrl: (data) => {
    const t = data.i18n[data.lang];
    const svc = t.services[data.pageKey];
    const text = svc ? t.servicePage.whatsappText.replace("{service}", svc.name) : t.lead.whatsappText;
    return `https://wa.me/${data.site.contact.whatsapp}?text=${encodeURIComponent(text)}`;
  },
  mailUrl: (data) => {
    const { emailSubject, emailBody } = data.i18n[data.lang].lead;
    return `mailto:${data.site.contact.email}?subject=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(emailBody)}`;
  },
  breadcrumbs: (data) => buildBreadcrumbs(data),
  faqItems: (data) => pageFaqs(data),
};

function buildJsonLd(data) {
  const { site, lang, pageKey, article } = data;
  const t = data.i18n[lang];
  const abs = (path) => new URL(path, site.url).href;
  const meta = pageMeta(data);
  const pageUrl = abs(alternates(data)[lang] || "/");
  const orgId = `${site.url}/#organization`;
  const inLanguage = site.hreflang[lang];

  const graph = [
    {
      "@type": "ProfessionalService",
      "@id": orgId,
      name: site.name,
      url: `${site.url}/`,
      logo: {
        "@type": "ImageObject",
        url: abs("/logos/meanify-logo.png"),
      },
      image: abs("/logos/meanify-logo.png"),
      email: site.contact.email,
      telephone: site.contact.phoneSchema,
      address: {
        "@type": "PostalAddress",
        streetAddress: site.contact.address.street,
        addressLocality: site.contact.address.locality,
        addressRegion: site.contact.address.region,
        addressCountry: site.contact.address.country,
      },
      areaServed: [
        { "@type": "Country", name: "Portugal" },
        { "@type": "Place", name: "European Union" },
      ],
      contactPoint: [
        {
          "@type": "ContactPoint",
          telephone: site.contact.phoneSchema,
          email: site.contact.email,
          contactType: "sales",
          availableLanguage: ["English", "Portuguese"],
        },
      ],
      description: t.faqPage.groups[0].items[0].a,
      slogan: t.home.hero.title,
      hasOfferCatalog: {
        "@type": "OfferCatalog",
        name: t.nav.services,
        itemListElement: site.services.map((key) => ({
          "@type": "Offer",
          itemOffered: {
            "@type": "Service",
            name: t.services[key].name,
            description: t.services[key].short,
            url: abs(site.pages[key][lang]),
          },
        })),
      },
      sameAs: [site.social.linkedin, site.social.facebook, `https://wa.me/${site.contact.whatsapp}`],
      knowsAbout: [
        "AI-accelerated software development",
        "Forward Deployed Engineering",
        "AI automation",
        "Multi-agent systems",
        "Data pipelines",
        "Data management",
        "Data governance",
        "Physical AI",
      ],
    },
    {
      "@type": "WebSite",
      "@id": `${site.url}/#website`,
      name: site.name,
      url: `${site.url}/`,
      publisher: { "@id": orgId },
      inLanguage: site.langs.map((l) => site.hreflang[l]),
    },
    {
      "@type": "WebPage",
      "@id": `${pageUrl}#webpage`,
      url: pageUrl,
      name: meta.title,
      description: meta.description,
      isPartOf: { "@id": `${site.url}/#website` },
      about: { "@id": orgId },
      inLanguage,
      dateModified: article ? article.updated : site.contentUpdated,
      primaryImageOfPage: abs(ogPath(data)),
    },
  ];

  if (article) {
    graph.push({
      "@type": "BlogPosting",
      "@id": `${pageUrl}#article`,
      headline: article.title,
      description: article.description,
      url: pageUrl,
      image: abs(ogPath(data)),
      datePublished: article.date,
      dateModified: article.updated,
      inLanguage,
      author: { "@id": orgId },
      publisher: { "@id": orgId },
      mainEntityOfPage: { "@id": `${pageUrl}#webpage` },
      keywords: article.keywords,
    });
  }

  const crumbs = buildBreadcrumbs(data);
  if (crumbs.length > 1) {
    graph.push({
      "@type": "BreadcrumbList",
      itemListElement: crumbs.map((c, i) => ({ "@type": "ListItem", position: i + 1, name: c.name, item: abs(c.url) })),
    });
  }

  const svc = t.services[pageKey];
  if (svc) {
    graph.push({
      "@type": "Service",
      "@id": `${pageUrl}#service`,
      name: svc.name,
      serviceType: svc.name,
      description: svc.lead,
      url: pageUrl,
      provider: { "@id": orgId },
      areaServed: [
        { "@type": "Country", name: "Portugal" },
        { "@type": "Place", name: "European Union" },
      ],
      availableLanguage: ["en", "pt"],
    });
  }

  if (pageKey === "services") {
    graph.push({
      "@type": "ItemList",
      itemListElement: site.services.map((key, i) => ({
        "@type": "ListItem",
        position: i + 1,
        name: t.services[key].name,
        url: abs(site.pages[key][lang]),
      })),
    });
  }

  const faqs = pageFaqs(data);
  if (faqs.length) {
    graph.push({
      "@type": "FAQPage",
      "@id": `${pageUrl}#faq`,
      inLanguage,
      mainEntity: faqs.map((f) => ({
        "@type": "Question",
        name: f.q,
        acceptedAnswer: { "@type": "Answer", text: f.a },
      })),
    });
  }

  return { "@context": "https://schema.org", "@graph": graph };
}

// Home → (parent) → current page, with names in the page language.
function buildBreadcrumbs(data) {
  const { site, lang, pageKey, article } = data;
  if (pageKey === "home") return [];
  const t = data.i18n[lang];
  const name = (key) => (t.services[key] ? t.services[key].name : t.meta[key].title.split(" | ")[0]);
  const shortName = (key) => t.nav[key] || name(key);
  const crumbs = [{ name: t.common.breadcrumbHome, url: site.pages.home[lang] }];
  const parent = site.parents[pageKey];
  if (parent) crumbs.push({ name: shortName(parent), url: site.pages[parent][lang] });
  crumbs.push(isArticle(data) ? { name: articleOf(data).title, url: articleOf(data).url || "/" } : { name: shortName(pageKey), url: site.pages[pageKey][lang] });
  return crumbs;
}

// FAQ entries shown (and marked up) on the page.
function pageFaqs(data) {
  const t = data.i18n[data.lang];
  const all = t.faqPage.groups.flatMap((g) => g.items);
  if (data.pageKey === "faq") return all;
  if (data.pageKey === "home") return t.home.faq.ids.map((id) => all.find((f) => f.id === id));
  if (isArticle(data)) return articleOf(data).faqs;
  const svc = t.services[data.pageKey];
  return svc ? svc.faqs : [];
}
